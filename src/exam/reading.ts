export function passageQuestions(p: Passage, seed: number): Question[] {
  const r = rng(seed);
  return p.questions.map((raw) => {
    const all = [raw.answer, ...raw.wrong];
    // "all of the answers" only makes sense as the last option
    const options = all.includes(ALL_CORRECT)
      ? [...shuffle(r, all.filter((o) => o !== ALL_CORRECT)), ALL_CORRECT]
      : shuffle(r, all);
    return {
      type: 'reading',
      prompt: raw.q,
      options,
      correct: options.indexOf(raw.answer),
      explain: raw.explain,
      passageId: p.id,
    };
  });
}

export const passageById = (id: string): Passage | undefined => PASSAGES.find((p) => p.id === id);

/** Reading section of a mock exam: two passages (12–14 questions, like the real 20-minute section). */
export function readingExam(seed: number): Question[] {
  const r = rng(seed ^ 0x5eed);
  return shuffle(r, PASSAGES)
    .slice(0, 2)
    .flatMap((p, i) => passageQuestions(p, seed + i));
}

